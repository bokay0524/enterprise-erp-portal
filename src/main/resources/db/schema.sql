DROP TABLE IF EXISTS asset_inspection;
DROP TABLE IF EXISTS asset_change_request;
DROP TABLE IF EXISTS fixed_asset;
DROP TABLE IF EXISTS inventory_stock;
DROP TABLE IF EXISTS sales_performance;
DROP TABLE IF EXISTS program_permission;
DROP TABLE IF EXISTS app_user;

CREATE TABLE app_user (
  user_id VARCHAR(30) PRIMARY KEY,
  password_salt VARCHAR(100) NOT NULL,
  password_hash VARCHAR(200) NOT NULL,
  display_name VARCHAR(60) NOT NULL,
  role VARCHAR(20) NOT NULL,
  department VARCHAR(60) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE program_permission (
  user_id VARCHAR(30) NOT NULL,
  permission_code VARCHAR(40) NOT NULL,
  PRIMARY KEY (user_id, permission_code),
  FOREIGN KEY (user_id) REFERENCES app_user(user_id)
);

CREATE TABLE sales_performance (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period VARCHAR(7) NOT NULL,
  division_name VARCHAR(40) NOT NULL,
  department_name VARCHAR(60) NOT NULL,
  target_amount DECIMAL(18,2) NOT NULL,
  actual_amount DECIMAL(18,2) NOT NULL
);

CREATE TABLE inventory_stock (
  item_code VARCHAR(30) PRIMARY KEY,
  item_name VARCHAR(120) NOT NULL,
  category VARCHAR(50) NOT NULL,
  warehouse VARCHAR(50) NOT NULL,
  stock_qty INT NOT NULL,
  reserved_qty INT NOT NULL,
  unit_price DECIMAL(18,2) NOT NULL,
  updated_at VARCHAR(19) NOT NULL
);

CREATE TABLE fixed_asset (
  asset_no VARCHAR(30) PRIMARY KEY,
  asset_name VARCHAR(120) NOT NULL,
  department VARCHAR(60) NOT NULL,
  owner_name VARCHAR(60) NOT NULL,
  location_name VARCHAR(100) NOT NULL,
  acquisition_date VARCHAR(10) NOT NULL,
  acquisition_cost DECIMAL(18,2) NOT NULL,
  asset_status VARCHAR(20) NOT NULL,
  last_inspected_date VARCHAR(10)
);

CREATE TABLE asset_change_request (
  request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_no VARCHAR(30) NOT NULL,
  requester_id VARCHAR(30) NOT NULL,
  requested_department VARCHAR(60) NOT NULL,
  requested_owner VARCHAR(60) NOT NULL,
  requested_location VARCHAR(100) NOT NULL,
  reason VARCHAR(500) NOT NULL,
  request_status VARCHAR(20) NOT NULL,
  requested_at VARCHAR(19) NOT NULL,
  decided_by VARCHAR(30),
  decided_at VARCHAR(19),
  FOREIGN KEY (asset_no) REFERENCES fixed_asset(asset_no)
);

CREATE TABLE asset_inspection (
  inspection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_no VARCHAR(30) NOT NULL,
  inspector_id VARCHAR(30) NOT NULL,
  inspection_result VARCHAR(20) NOT NULL,
  remark VARCHAR(500),
  inspected_at VARCHAR(19) NOT NULL,
  FOREIGN KEY (asset_no) REFERENCES fixed_asset(asset_no)
);
